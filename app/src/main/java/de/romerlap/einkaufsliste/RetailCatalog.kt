        val lower = name.lowercase()
        val tokens = lower.split(Regex("[^a-zäöüß]+")).filter { it.isNotEmpty() }
        if (tokens.any { it == "ei" } || lower.contains("eier")) {
            return "6er- oder 10er-Packung"
        }
        for ((key, hint) in entries) {
            if (lower.contains(key)) return hint
        }
        return null
    }

